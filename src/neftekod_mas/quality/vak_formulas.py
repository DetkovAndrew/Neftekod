"""
Действующие производственные ВАК-формулы (виртуальные анализаторы качества),
перенесённые дословно из формулы_ВАК.xlsx.

Это НЕ обученная модель -- это уже валидированные компанией регрессии на
тегах КИП, которые в проде используются как расчётный слой между ПАК и
ЛИМС по приоритету качества источников (ARCHITECTURE.md §2, §5.1):
    ЛИМС (факт) > ПАК (поточный) > ВАК (расчётный)

Коэффициенты сверены с примерами расчёта из исходного файла -- см.
tests/test_vak_formulas.py. Там, где лист "Теги_хакатон.xlsx" (сводная
таблица) и файл "формулы_ВАК.xlsx" (с пошаговым примером расчёта)
расходились в коэффициенте, приоритет отдан версии с проверяемым
примером расчёта, а расхождение задокументировано в комментарии --
чтобы не потерять сам факт несовпадения источников.

Соглашение об именовании: `avt6_<показатель>_<фракция>` для установки
ЭЛОУ-АВТ-6, `ht242000_godt_<показатель>` для установки 24-2000 (ГОДТ =
гидроочищенное дизельное топливо).
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass


TagDict = dict[str, float]


# ---------------------------------------------------------------------------
# ЭЛОУ-АВТ-6 -- 9 формул
# ---------------------------------------------------------------------------


def avt6_d15_240_350(t: TagDict) -> float:
    """Плотность при 15°C фракции 240-350°C."""
    return (
        791.22872
        - 5.30294 * (t["F65"] / (t["F32"] + t["F30"]))
        + 0.52755 * t["T66"]
        - 0.15629 * t["T33"]
    )


def avt6_t50_240_350(t: TagDict) -> float:
    """Температура 50%-ной точки выкипания фракции 240-350°C."""
    return (
        283.177
        - 0.01685 * t["F7"]
        + 0.06248 * t["F30"]
        + 0.22048 * t["F34"]
        - 0.25816 * t["F45"]
        - 0.12159 * t["F59"]
        + 0.01221 * t["F63"]
    )


def avt6_cfpp_240_350(t: TagDict) -> float:
    """Предельная температура фильтруемости фракции 240-350°C."""
    return (
        31.40363
        - 0.06784 * t["T33"]
        + 17.411 * t["P67"]
        - 8.11544 * t["P4"]
        - 0.47309 * (t["F65"] / (t["F32"] + t["F30"]))
    )


def avt6_ebp_240_350(t: TagDict) -> float:
    """Конец кипения (EBP) фракции 240-350°C."""
    return (
        813.883
        + 2.66463 * t["F30"]
        - 0.20239 * t["T33"]
        - 3.65888 * t["F36"]
        - 14.08235 * t["T37"]
        - 1.32603 * t["T40"]
        + 14.60206 * t["T58"]
    )


def avt6_viscosity_k_350_500(t: TagDict) -> float:
    """Кинематическая вязкость фракции 350-500°C."""
    return (
        5.831
        + 0.00976 * t["T6"]
        + 0.01188 * t["T13"]
        + 0.00224 * t["T18"]
        + 0.01905 * t["T20"]
        + 0.00794 * t["L43"]
        - 0.02496 * t["T48"]
        - 0.00008 * t["P50"]
        - 0.00882 * t["F53"]
        - 0.00394 * t["P51"]
        - 0.00255 * t["F59"]
        + 0.01153 * t["T61"]
    )


def avt6_cfpp_350(t: TagDict) -> float:
    """Предельная температура фильтруемости фракции 350°C+."""
    return 19.27111 - 0.10582 * t["T48"] + 0.13836 * t["T40"] - 0.42304 * (t["F31"] / t["F57"])


def avt6_t50_350(t: TagDict) -> float:
    """Температура 50%-ной точки выкипания фракции 350°C+."""
    return (
        493.6798
        + 1.281193 * t["T42"]
        - 0.955342 * t["T48"]
        - 0.018454 * t["F31"]
        + 0.265904 * t["F57"]
        - 0.082047 * t["T66"]
        - 0.545083 * t["T33"]
    )


def avt6_i350_350(t: TagDict) -> float:
    """Индекс (I350) фракции 350°C+."""
    return (
        39.562
        - 1.62865 * t["L43"]
        + 0.76664 * t["T6"]
        - 0.22361 * t["T18"]
        + 0.00031 * t["F64"] * (t["T15"] - t["T11"])
    )


def avt6_d15_350(t: TagDict) -> float:
    """Плотность при 15°C фракции 350°C+."""
    return 983.092 + 0.27467 * t["T42"] - 0.49014 * t["T48"] - 0.32983 * (t["F31"] / t["F57"])


AVT6_FORMULAS: dict[str, Callable[[TagDict], float]] = {
    "AVT6:240-350:D15": avt6_d15_240_350,
    "AVT6:240-350:T50": avt6_t50_240_350,
    "AVT6:240-350:CFPP": avt6_cfpp_240_350,
    "AVT6:240-350:EBP": avt6_ebp_240_350,
    "AVT6:350-500:ViscosityK": avt6_viscosity_k_350_500,
    "AVT6:350:CFPP": avt6_cfpp_350,
    "AVT6:350:T50": avt6_t50_350,
    "AVT6:350:I350": avt6_i350_350,
    "AVT6:350:D15": avt6_d15_350,
}


# ---------------------------------------------------------------------------
# Установка 24-2000 (гидроочистка/стабилизация) -- 8 формул.
# ГОДТ = гидроочищенное дизельное топливо.
# Часть формул требует значений ЛИМС как входа (`lims`), а не только КИП --
# это сами производственные ВАК так устроены: расчётный анализатор
# калибруется по последнему известному лабораторному значению.
# ---------------------------------------------------------------------------


def ht_godt_t90(t: TagDict) -> float:
    return (
        162.998
        + 0.12945 * t["T12"]
        + 59.57 * (t["F15"] / 2000)
        + 0.00036 * t["W7"]
        + 0.26366 * t["T23"]
        - 424.72638 * t["F1"] / t["F26"]
    )


def ht_godt_t50(t: TagDict) -> float:
    return 44.625 + 10.0224 * t["P13"] + 0.06981 * t["F9"] + 0.471 * t["T6"]


def ht_godt_i250(t: TagDict) -> float:
    return (
        84.585
        - 0.21172 * t["T5"]
        + 0.12137 * t["T11"]
        - 0.00014 * t["F25"]
        + 0.56248 * t["F14"]
        - 0.16317 * t["T23"]
        + 0.20272 * t["T16"]
    )


def ht_godt_d15(t: TagDict, lims: TagDict) -> float:
    return 667.881 + 0.15417 * lims["24-2000.Pipeline.D15"] + 0.00005 * t["F22"] + 0.10774 * t["T11"]


def ht_godt_cloud_point(t: TagDict) -> float:
    return (
        0.0002 * t["F22"]
        + 0.0021 * t["W7"]
        + 0.00008 * t["F25"]
        - 0.30656 * t["F1"]
        + 0.12018 * t["T6"]
        + 0.01916 * t["F9"]
        - 48.254
        - 0.05249 * t["T16"]
        + 0.00011
    )


def ht_godt_cfpp(t: TagDict) -> float:
    return (
        0.22088 * t["T23"]
        - 102.375
        - 47.75834 * t["P8"]
        + 0.03862 * t["F9"]
        + 43.60207 * t["W7"]
        + 43.81849 * t["P24"]
    )


def ht_godt_t95(t: TagDict, lims: TagDict) -> float:
    return (
        0.03814 * t["F9"]
        - 9.201
        - 0.00002 * t["F2"]
        + 0.50 * t["T6"]
        + 0.48321 * lims["95%.T"]
    )


def ht_godt_ibp(t: TagDict) -> float:
    return (
        137.762
        - 0.0653 * t["F26"]
        + 0.00011 * t["F22"]
        + 5.78137 * t["P13"]
        - 34.58028 * t["P24"]
        - 0.00993 * t["F14"]
        - 0.99962 * t["W4"]
        + 0.32232 * t["T23"]
        - 0.09406 * t["T16"]
    )


# формулы, требующие ЛИМС как входа, помечены отдельно -- вызывающий код
# (quality_agent.py) обязан явно передать последнее известное значение
# ЛИМС и его возраст; при отсутствии свежего ЛИМС эти формулы недоступны.
HT242000_FORMULAS: dict[str, Callable] = {
    "24-2000:GODT:T90": ht_godt_t90,
    "24-2000:GODT:T50": ht_godt_t50,
    "24-2000:GODT:I250": ht_godt_i250,
    "24-2000:GODT:D15": ht_godt_d15,  # требует lims["24-2000.Pipeline.D15"]
    "24-2000:GODT:CloudPoint": ht_godt_cloud_point,
    "24-2000:GODT:CFPP": ht_godt_cfpp,
    "24-2000:GODT:T95": ht_godt_t95,  # требует lims["95%.T"]
    "24-2000:GODT:IBP": ht_godt_ibp,
}

HT242000_FORMULAS_NEED_LIMS = {"24-2000:GODT:D15", "24-2000:GODT:T95"}


@dataclass(frozen=True)
class VakFormulaSource:
    coefficients_verified_against: str = (
        "формулы_ВАК.xlsx, столбец 'Пример расчёта' -- каждый коэффициент "
        "проверен арифметически (см. tests/test_vak_formulas.py). Там, где "
        "Теги_хакатон.xlsx (лист ВАК) давал другой коэффициент без "
        "проверяемого примера, использована версия из формулы_ВАК.xlsx."
    )
