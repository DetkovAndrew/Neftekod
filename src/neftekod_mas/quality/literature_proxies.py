"""
Литературные прокси-зависимости -- НЕ производственные ВАК-формулы.

Единственный случай в системе v1: сера в гидроочищенном ДТ не имеет
ни ПАК-резерва в... (есть, `24-2000:Mg.Sulfur`), ни ВАК-формулы вовсе
(см. quality_agent.py docstring и ARCHITECTURE.md §5.2.1) -- значит,
Агент оптимизации в принципе не может КОЛИЧЕСТВЕННО оценить эффект
изменения температуры реактора на серу через приоритетный слой
(ЛИМС -> ПАК -> ВАК). При этом именно эта зависимость -- ключевая тема
Q&A-сессии (вопрос №32 транскрипта): "температура реактора гидроочистки
на 1 градус снижает серу примерно на 3-10% (литература)". Ответ
эксперта на "какая величина ближе к вашей практике" не расшифровывается
в транскрипте (аудио неразборчиво), поэтому берётся СЕРЕДИНА
заявленного литературного диапазона (7.5% относительного снижения на
1°C) как явное, качественное, НЕ подтверждённое практикой допущение.

Это единственное место в кодовой базе, где количественная зависимость
взята не из выданных материалов (ВАК-формулы/тег-справочник), а
непосредственно из формулировки вопроса на Q&A-сессии. Использовать
с крайней осторожностью: source=LITERATURE_PROXY, confidence всегда
LOW, кандидат всегда сопровождается явной оговоркой оператору.
"""

from __future__ import annotations

LITERATURE_RATE_PCT_PER_C = 0.075  # середина диапазона 5-10%/°C, вопрос №32 Q&A-транскрипта
LITERATURE_RATE_RANGE = (0.03, 0.10)  # ТЗ-транскрипт цитирует и "3-10 мг/кг", и "5-10%"; берём относительный вариант


def sulfur_after_reactor_temp_change(baseline_sulfur_mg_kg: float, delta_t_c: float) -> float:
    """Оценка серы после изменения температуры реактора Р-202 на delta_t_c
    (положительное delta_t = нагрев = снижение серы, по литературной
    зависимости, НЕ подтверждённой экспертом на Q&A). Не может дать
    отрицательное значение."""
    factor = 1.0 - LITERATURE_RATE_PCT_PER_C * delta_t_c
    return max(0.0, baseline_sulfur_mg_kg * factor)
