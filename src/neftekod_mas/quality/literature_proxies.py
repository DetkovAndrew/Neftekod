"""
Литературные прокси-зависимости -- НЕ производственные ВАК-формулы и
НЕ опубликованные отраслевые стандарты (см. astm_correlations.py).

Сера в гидроочищенном ДТ не имеет ни ВАК-формулы (см. quality_agent.py
docstring и ARCHITECTURE.md §5.2.1), ни производственной калибровки --
значит, Агент оптимизации в принципе не может количественно оценить
эффект изменения температуры реактора на серу через приоритетный слой
(ЛИМС -> ПАК -> ВАК). Здесь -- физически обоснованная (Аррениус),
но не подтверждённая экспертом завода модель, собранная из открытой
литературы по кинетике гидрообессеривания (ГДС).

Модель. Для гидрообессеривания в псевдо-первом порядке по сере
(стандартное приближение, см. ниже про ограничения):
    S_out = S_in * exp(-k(T)*tau),   k(T) = A*exp(-Ea/(R*T))
Пусть "тяжесть" текущего режима -- severity = ln(S_in/S_out) = k(T)*tau
(вычисляется из РЕАЛЬНЫХ ЛИМС: сера на входе в ГО, точка 1, параметр
Mass.Sulfur, % масс., и сера на выходе, точка 2, Mg.Sulfur, мг/кг --
обе точки ЕСТЬ в выданных материалах, см. quality_agent.GODT_POINT2
и quality_agent.HT_FEED_POINT). Тогда для малого изменения температуры
dT реактора:
    d(ln S_out)/dT = -severity * Ea/(R*T^2)
    S_out(T+dT) = S_out(T) * exp(-severity * Ea/(R*T^2) * dT)

Активационная энергия Ea. Взята из открытой литературы по кинетике ГДС
дизельных фракций на NiMo/Al2O3 катализаторах (диапазон условий:
300-360°C, 4.4-7.4 МПа, LHSV 0.75-12 ч^-1 -- близко к параметрам нашей
установки 24-2000): Ea = 47.24-66.13 кДж/моль (пре-экспоненты
6.515-15.62e4 ч^-1). Источник: промышленные данные, степенная кинетика
с температурной зависимостью по Аррениусу для гидрирования серо- и
азотсодержащих соединений. Взята середина диапазона, 55 кДж/моль, как
явное, документированное допущение (НЕ подобрано под конкретный завод).

Перекрёстная проверка с Q&A. Вопрос №32 Q&A-транскрипта цитирует
литературу "1°C реактора -> 3-10 мг/кг или 5-10% относительного
снижения серы", ответ эксперта неразборчив. При типичной температуре
~370°C (643 K) и severity~4-6 (типичное для глубокой очистки до
<10 мг/кг при сырье ~0.3-0.8% масс.) эта Аррениус-модель даёт
относительную чувствительность порядка 5-10%/°C -- то есть НЕЗАВИСИМАЯ
литературная кинетика (кДж/моль активации ГДС) количественно
согласуется с независимо процитированным на Q&A диапазоном. Это
взаимное подтверждение ДВУХ независимых источников, а не один и тот же
факт, посчитанный дважды -- существенно повышает доверие к модели
по сравнению с использованием только одного из источников.

Ограничения (честно, не спрятаны). (1) Псевдо-первый порядок -- в
реальности глубокое ГДС часто имеет более высокий порядок по сере и
ингибирование H2S/азотом/ароматикой (см. цитированную литературу) --
упрощение, которое, видимо, СИСТЕМАТИЧЕСКИ занижает чувствительность
при очень низких концентрациях серы (модель скорее консервативна,
чем оптимистична). (2) tau (время пребывания) предполагается
постоянным -- при изменении расхода сырья это неверно, модель
применяется только к изменению ТЕМПЕРАТУРЫ реактора, не расхода.
(3) Ea не откалибрована по ЭТОМУ заводу/катализатору. Confidence
всегда LOW, кандидат всегда сопровождается явной оговоркой оператору
(см. optimization_agent.py).
"""

from __future__ import annotations

import math

GAS_CONSTANT_J_MOL_K = 8.314

# Середина диапазона 47.24-66.13 кДж/моль, см. docstring модуля.
HDS_ACTIVATION_ENERGY_J_MOL = 55_000.0

# Резервная (упрощённая) оценка -- используется только если нет свежего
# ЛИМС по сере НА ВХОДЕ в гидроочистку (точка 1), и поэтому severity
# посчитать нечем. Тот же диапазон 5-10%/°C из Q&A вопроса №32,
# середина.
FALLBACK_RATE_PCT_PER_C = 0.075


def hds_severity(feed_sulfur_pct_mass: float, product_sulfur_mg_kg: float) -> float:
    """severity = ln(S_in/S_out), безразмерная 'тяжесть' режима ГДС
    (эквивалент k*tau псевдо-первого порядка). S_in переводится из
    % масс. в мг/кг (1% = 10000 мг/кг, точное соотношение по массе)."""
    feed_sulfur_mg_kg = feed_sulfur_pct_mass * 10_000.0
    if product_sulfur_mg_kg <= 0 or feed_sulfur_mg_kg <= 0:
        raise ValueError("Сера должна быть положительной для расчёта severity")
    return math.log(feed_sulfur_mg_kg / product_sulfur_mg_kg)


def sulfur_after_reactor_temp_change_arrhenius(
    product_sulfur_mg_kg: float,
    severity: float,
    current_temp_c: float,
    delta_t_c: float,
    ea_j_mol: float = HDS_ACTIVATION_ENERGY_J_MOL,
) -> float:
    """Оценка серы на выходе после изменения температуры реактора на
    delta_t_c, по Аррениус-чувствительности при текущей 'тяжести'
    режима severity (см. docstring модуля). Положительное delta_t_c
    (нагрев) снижает серу."""
    t_kelvin = current_temp_c + 273.15
    sensitivity_per_c = severity * ea_j_mol / (GAS_CONSTANT_J_MOL_K * t_kelvin ** 2)
    return product_sulfur_mg_kg * math.exp(-sensitivity_per_c * delta_t_c)


def sulfur_after_reactor_temp_change_flat(baseline_sulfur_mg_kg: float, delta_t_c: float) -> float:
    """Резервная плоская оценка (используется, если нет свежего ЛИМС по
    сере на входе -- см. docstring модуля). Не может дать отрицательное
    значение."""
    factor = 1.0 - FALLBACK_RATE_PCT_PER_C * delta_t_c
    return max(0.0, baseline_sulfur_mg_kg * factor)


# ---------------------------------------------------------------------------
# Заводская калибровка (ARCHITECTURE.md §6.4.1)
# ---------------------------------------------------------------------------
#
# Литературная модель выше физически обоснована, но на истории ЭТОЙ
# установки она оказалась ОПТИМИСТИЧНОЙ: измеренный отклик поточного
# анализатора серы Q21 на ступени температуры реактора даёт
# чувствительность в разы меньше (scripts/compute_sulfur_temperature_response.py).
# Важно, что расхождение объясняется, а не замалчивается: установка
# работает в замкнутом контуре регулирования (подтверждено и на Q&A, и
# измеренной корреляцией "температуру поднимают, когда сера высокая"),
# а такая обратная связь смещает наблюдаемый отклик к нулю. То есть
# истинная чувствительность лежит МЕЖДУ измеренной и литературной.
#
# Практический вывод для безопасности: обещать оператору литературный
# эффект нельзя. Если система заявит, что +4 °C уберут серу с 10 до 6.6,
# а на деле уберут до 9.1, оператор не примет нужных дополнительных мер.
# Занижение эффекта, наоборот, ведёт лишь к более раннему или более
# сильному воздействию. Поэтому для проверки "устраняет ли кандидат
# нарушение" берётся КОНСЕРВАТИВНАЯ (меньшая по модулю) оценка.


def sulfur_after_reactor_temp_change_plant_calibrated(
    baseline_sulfur_mg_kg: float, delta_t_c: float, pct_per_c: float
) -> float:
    """Отклик серы по измеренной на этой установке чувствительности.

    `pct_per_c` -- относительное изменение серы на градус в процентах,
    отрицательное (рост температуры снижает серу); берётся из
    `config/sulfur_temp_response.yaml`, ключ `plant_calibrated_pct_per_c`.
    """
    if baseline_sulfur_mg_kg <= 0:
        raise ValueError("Базовая сера должна быть положительной")
    return float(baseline_sulfur_mg_kg * (1.0 + pct_per_c / 100.0) ** delta_t_c)


def conservative_sulfur_prediction(
    literature_value_mg_kg: float, plant_value_mg_kg: float, baseline_sulfur_mg_kg: float
) -> float:
    """Из двух прогнозов выбирает тот, который обещает МЕНЬШЕ улучшения.

    Для подъёма температуры (сера снижается) это больший из двух
    прогнозов; для снижения температуры (сера растёт) -- тоже больший,
    то есть худший для качества. В обоих случаях это одно и то же
    правило `max`, и оно всегда работает в сторону осторожности,
    независимо от знака воздействия.
    """
    return float(max(literature_value_mg_kg, plant_value_mg_kg))
