"""
Опубликованные отраслевые (ASTM) корреляции -- третья, отдельная от
`vak_formulas.py` (производственные формулы завода) и
`literature_proxies.py` (оценки из формулировки вопроса на Q&A),
категория источников: признанные, стандартизированные методы оценки
показателей качества, не специфичные для конкретного завода.

ASTM D976-91: Standard Test Method for Calculated Cetane Index of
Distillate Fuels (см. archive.org/stream/gov.law.astm.d976.1991).
Формула на основе плотности при 15°C и температуры 50%-ной точки
выкипания (mid-boiling point). Выбрана вместо более новой/точной
ASTM D4737 (four-variable, ±2 CN у 65% топлив), потому что D4737
требует T10 (10%-ную точку выкипания), которой нет ни в ЛИМС, ни в
ВАК-формулах установки 24-2000 -- а D976 нужны только D15 и T50, обе
из которых у нас уже есть (ЛИМС/ПАК/GODT:D15/GODT:T50).

Коэффициенты формулы (metric/Celsius вариант) сверены вручную по
численному примеру из самого стандарта (API=33.0, mid b.pt=557.14°F
-> CCI=48.52 по формуле в градусах Фаренгейта; тот же пример,
пересчитанный в D=0.8602 г/мл, B=291.74°C, даёт CCI≈48.6 по формуле
в градусах Цельсия -- два независимых представления одного стандарта
сходятся с точностью до долей единицы, что подтверждает правильность
переноса коэффициентов и единиц измерения).

Точность по самому стандарту (диапазон 30-60 CN): в пределах ±2 CN
для ~75% топлив. Насколько это верно для КОНКРЕТНОГО завода и сырья --
проверено отдельно на реальных данных, см.
scripts/compute_astm_cetane_accuracy.py и
config/astm_cetane_accuracy.yaml.
"""

from __future__ import annotations

import math


def cetane_index_d976(density_15c_g_ml: float, mid_boiling_point_c: float) -> float:
    """ASTM D976, формула в метрических единицах (D в г/мл, B в °C)."""
    d, b = density_15c_g_ml, mid_boiling_point_c
    return (
        454.74
        - 1641.416 * d
        + 774.74 * d ** 2
        - 0.554 * b
        + 97.803 * (math.log10(b)) ** 2
    )
